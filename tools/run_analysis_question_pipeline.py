def shell_join(args: list[str]) -> str:
    return subprocess.list2cmdline(args)


def load_successful_questions() -> set[str]:
    successful = set()
    if not STATUS_FILE.exists():
        return successful

    with STATUS_FILE.open("r", encoding="utf-8") as fh:
        for line in fh:
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if record.get("returncode") == 0 and record.get("question"):
                successful.add(record["question"])
    return successful


def append_status(record: dict) -> None:
    RUN_DIR.mkdir(parents=True, exist_ok=True)
    with STATUS_FILE.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")


def safe_log_name(index: int, question: str) -> str:
    slug = re.sub(r"[^0-9A-Za-zА-Яа-яЁё]+", "_", question, flags=re.UNICODE).strip("_")
    slug = slug[:80] or "question"
    digest = hashlib.sha1(question.encode("utf-8")).hexdigest()[:8]
    return f"{index:04d}_{slug}_{digest}.log"


def select_questions(start: int, limit: int | None) -> list[tuple[int, str]]:
    if start < 1:
        raise ValueError("--start is 1-based and must be >= 1")
    selected = list(enumerate(QUESTIONS, start=1))[start - 1 :]
    if limit is not None:
        selected = selected[:limit]
    return selected


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Sequentially run pipeline/enrichment_coordinator.py over a broad math analysis object list."
    )
    parser.add_argument("--dry-run", action="store_true", help="Print commands without running them.")
    parser.add_argument("--list", action="store_true", help="Print the generated object list and exit.")
    parser.add_argument("--resume", action="store_true", help="Skip objects already recorded as successful.")
    parser.add_argument("--start", type=int, default=1, help="1-based object index to start from.")
    parser.add_argument("--limit", type=int, default=None, help="Maximum number of objects to run.")
    parser.add_argument("--stop-on-fail", action="store_true", help="Stop after the first failed pipeline run.")
    parser.add_argument(
        "--python-exe",
        type=Path,
        default=DEFAULT_PYTHON_EXE,
        help="Python executable used to run pipeline/enrichment_coordinator.py.",
    )
    parser.add_argument(
        "--questions-out",
        type=Path,
        default=None,
        help="Optional path for saving the generated object list as UTF-8 text.",
    )
    args = parser.parse_args()

    if args.questions_out:
        args.questions_out.parent.mkdir(parents=True, exist_ok=True)
        args.questions_out.write_text("\n".join(QUESTIONS) + "\n", encoding="utf-8")

    if args.list:
        for index, question in enumerate(QUESTIONS, start=1):
            print(f"{index:04d}. {question}")
        print(f"\nTotal: {len(QUESTIONS)}")
        return 0

    python_exe = args.python_exe
    if not python_exe.is_absolute():
        python_exe = PROJECT_ROOT / python_exe
    if not python_exe.exists():
        print(f"Python executable not found: {python_exe}", file=sys.stderr)
        return 2
    if not WRAPPER.exists():
        print(f"Wrapper not found: {WRAPPER}", file=sys.stderr)
        return 2
    if not RERANKER_MODEL.exists():
        print(f"Reranker model not found: {RERANKER_MODEL}", file=sys.stderr)
        return 2

    RUN_DIR.mkdir(parents=True, exist_ok=True)
    selected = select_questions(args.start, args.limit)
    successful = load_successful_questions() if args.resume else set()

    print(f"Objects total: {len(QUESTIONS)}")
    print(f"Selected for this run: {len(selected)}")
    print(f"Logs: {RUN_DIR}")

    failures = 0
    for index, question in selected:
        if question in successful:
            print(f"[{index:04d}/{len(QUESTIONS):04d}] skip successful: {question}")
            continue

        cmd = command_for(question, python_exe)
        log_path = RUN_DIR / safe_log_name(index, question)
        print(f"[{index:04d}/{len(QUESTIONS):04d}] run: {question}")
        print(f"  log: {log_path}")

        if args.dry_run:
            print(f"  command: {shell_join(cmd)}")
            continue

        started = time.time()
        started_at = datetime.now().isoformat(timespec="seconds")
        with log_path.open("w", encoding="utf-8", errors="replace") as log:
            log.write(f"# object: {question}\n")
            log.write(f"# started_at: {started_at}\n")
            log.write(f"# command: {shell_join(cmd)}\n\n")
            log.flush()
            proc = subprocess.run(
                cmd,
                cwd=PROJECT_ROOT,
                stdout=log,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
            )

        elapsed = round(time.time() - started, 2)
        record = {
            "index": index,
            "question": question,
            "returncode": proc.returncode,
            "elapsed_seconds": elapsed,
            "started_at": started_at,
            "finished_at": datetime.now().isoformat(timespec="seconds"),
            "log": str(log_path),
        }
        append_status(record)

        if proc.returncode == 0:
            print(f"  ok in {elapsed}s")
        else:
            failures += 1
            print(f"  failed with code {proc.returncode} in {elapsed}s")
            if args.stop_on_fail:
                return proc.returncode

    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
