def build_questions() -> list[str]:
    objects: list[str] = []
    for section in ANALYSIS_PLAN.values():
        for kind, label in TYPE_LABELS.items():
            for topic in section.get(kind, []):
                objects.append(f"{label}: {topic}")
    return dedupe_preserve_order(objects)


def dedupe_preserve_order(items: list[str]) -> list[str]:
    seen = set()
    result = []
    for item in items:
        normalized = " ".join(item.casefold().split())
        if normalized not in seen:
            seen.add(normalized)
            result.append(item)
    return result


